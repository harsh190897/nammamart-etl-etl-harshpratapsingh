"""
analysis/business_questions.py
------------------------------
Answers the six business questions from BOTH pipelines' final tables, checks that ETL and ELT give the
same answers, and compares the September totals (Part B4).

Run from the project root, when no DAG is running (DuckDB allows one writer, and this script only reads):
    python analysis/business_questions.py                      # print the results
    python analysis/business_questions.py --update-submission  # also write them into SUBMISSION.md

The SQL for every question is in analysis/sql/ (q<N>_etl.sql and q<N>_elt.sql).
"""
import argparse
import re
import sys
from pathlib import Path

import duckdb
import pandas as pd

PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT / "include"))
import nammamart_common as nc  # noqa: E402

SQL_DIR = Path(__file__).resolve().parent / "sql"
SUBMISSION = PROJECT / "SUBMISSION.md"
START, END = "<!-- business-questions:start -->", "<!-- business-questions:end -->"

QUESTIONS = [
    ("Q1", "Daily net revenue by zone and by store (delivered orders only, after discount)", 10),
    ("Q2", "Revenue and gross margin by product category (margin = revenue − quantity × cost_price)", None),
    ("Q3", "Average delivery time per store, and the % of delivered orders within 15 minutes", None),
    ("Q4", "Revenue by payment mode, and the total amount that doesn't reconcile with the payment gateway", None),
    ("Q5", "Top 10 customers by spend, with loyalty tier (no raw email or phone shown)", None),
    ("Q6", "Number of rows rejected today, by file and by reason", None),
]


def connect():
    con = duckdb.connect(str(nc.WAREHOUSE_DB), read_only=True)
    con.execute("SET VARIABLE quarantine_glob = ?", [str(nc.QUARANTINE_DIR / "*_failed_*.csv")])
    return con


def run(con, name: str) -> pd.DataFrame:
    return con.execute((SQL_DIR / name).read_text()).df()


def same(etl: pd.DataFrame, elt: pd.DataFrame) -> bool:
    try:
        pd.testing.assert_frame_equal(etl.reset_index(drop=True), elt.reset_index(drop=True),
                                      check_dtype=False, check_exact=False, atol=0.005)
        return True
    except AssertionError:
        return False


def fmt(value) -> str:
    if value is None or (not isinstance(value, str) and pd.isna(value)):
        return ""
    if isinstance(value, float):
        return f"{value:,.2f}"
    if isinstance(value, int):
        return f"{value:,}"
    if hasattr(value, "strftime"):
        return value.strftime("%Y-%m-%d")
    return str(value)


def to_markdown(df: pd.DataFrame, limit=None) -> str:
    shown = df if limit is None else df.head(limit)
    lines = ["| " + " | ".join(shown.columns) + " |", "|" + "---|" * len(shown.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in shown.itertuples(index=False)]
    if limit is not None and len(df) > limit:
        lines.append(f"\n_First {limit} of {len(df):,} rows._")
    return "\n".join(lines)


def sql_block(name: str) -> str:
    return "```sql\n" + (SQL_DIR / name).read_text().strip() + "\n```"


def build_report(con) -> tuple:
    parts, all_match = [], True
    latest = con.execute("""SELECT dag_id, max(run_id) FILTER (WHERE start_time = last_start) AS run_id
                            FROM (SELECT *, max(start_time) OVER (PARTITION BY dag_id) AS last_start
                                  FROM pipeline_runs WHERE status = 'SUCCESS') GROUP BY dag_id ORDER BY dag_id""").fetchall()
    parts.append("Results below are from the latest successful run of each DAG: "
                 + "; ".join(f"`{dag}` run `{run_id}`" for dag, run_id in latest)
                 + ". Generated by [`analysis/business_questions.py`](analysis/business_questions.py) "
                   "from the SQL in [`analysis/sql/`](analysis/sql/).")

    for code, title, limit in QUESTIONS:
        etl_file, elt_file = f"{code.lower()}_etl.sql", f"{code.lower()}_elt.sql"
        etl, elt = run(con, etl_file), run(con, elt_file)
        match = same(etl, elt)
        all_match &= match
        verdict = ("✅ ETL and ELT return **identical** results." if match
                   else "⚠️ ETL and ELT results **differ**: see the two tables.")
        parts.append(f"### {code}. {title}\n\n{verdict}\n\n"
                     f"<details><summary>SQL</summary>\n\n**ETL** ([`analysis/sql/{etl_file}`](analysis/sql/{etl_file}))\n\n"
                     f"{sql_block(etl_file)}\n\n**ELT** ([`analysis/sql/{elt_file}`](analysis/sql/{elt_file}))\n\n"
                     f"{sql_block(elt_file)}\n\n</details>\n\n"
                     f"**Result{' (ETL and ELT)' if match else ' (ETL)'}:**\n\n{to_markdown(etl, limit)}"
                     + ("" if match else f"\n\n**Result (ELT):**\n\n{to_markdown(elt, limit)}"))
        print(f"{code}: {'MATCH' if match else 'DIFFERENT'} ({len(etl)} ETL rows, {len(elt)} ELT rows)")

    totals, zones = run(con, "september_totals.sql"), run(con, "september_by_zone.sql")
    print(totals.to_string(index=False))
    print(zones.to_string(index=False))
    parts.append("### ETL vs ELT totals for September 2026 (Part B4)\n\n"
                 f"<details><summary>SQL</summary>\n\n{sql_block('september_totals.sql')}\n\n"
                 f"{sql_block('september_by_zone.sql')}\n\n</details>\n\n"
                 f"{to_markdown(totals)}\n\n{to_markdown(zones)}")
    return "\n\n".join(parts), all_match


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update-submission", action="store_true", help="write the results into SUBMISSION.md")
    args = parser.parse_args()

    con = connect()
    try:
        report, all_match = build_report(con)
    finally:
        con.close()
    print("All six questions:", "ETL and ELT MATCH" if all_match else "SOME DIFFER")

    if args.update_submission:
        text = SUBMISSION.read_text()
        if START not in text or END not in text:
            raise SystemExit(f"Markers {START} / {END} not found in SUBMISSION.md")
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: f"{START}\n\n{report}\n\n{END}",
                      text, flags=re.S)
        SUBMISSION.write_text(text)
        print(f"Updated {SUBMISSION.name}")


if __name__ == "__main__":
    main()
